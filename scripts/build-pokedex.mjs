// Generates public/assets/js/pokedex.js: a compact, static copy of the PokéAPI data the game needs.
// Run with `node scripts/build-pokedex.mjs` whenever new Pokémon are released.
import { writeFile } from "node:fs/promises";

const API = "https://pokeapi.co/api/v2/";
const CONCURRENCY = 16;
const OUT = new URL("../public/assets/js/pokedex.js", import.meta.url);

async function getJson(url) {
    for (let attempt = 1; ; attempt++) {
        try {
            const response = await fetch(url);
            if (!response.ok) throw new Error(`${response.status} ${url}`);
            return await response.json();
        } catch (error) {
            if (attempt >= 4) throw error;
            await new Promise(resolve => setTimeout(resolve, 500 * attempt));
        }
    }
}

// Default forms have ids 1..N where N is the number of species; alternate forms start at 10001.
const { count } = await getJson(`${API}pokemon-species?limit=1`);
const ids = Array.from({ length: count }, (_, i) => i + 1);

const pokedex = new Array(count);
let done = 0;
async function worker() {
    while (ids.length) {
        const id = ids.shift();
        const p = await getJson(`${API}pokemon/${id}`);
        pokedex[id - 1] = {
            id: p.id,
            name: p.name,
            types: p.types.sort((a, b) => a.slot - b.slot).map(t => t.type.name),
            abilities: p.abilities.sort((a, b) => a.slot - b.slot).map(a => a.ability.name),
        };
        if (++done % 100 === 0) console.log(`${done}/${count}`);
    }
}
await Promise.all(Array.from({ length: CONCURRENCY }, worker));

const body = pokedex.map(p => JSON.stringify(p)).join(",\n");
await writeFile(OUT, `"use strict";\n\n// Generated by scripts/build-pokedex.mjs, do not edit by hand.\nconst POKEDEX = [\n${body}\n];\n`);
console.log(`Wrote ${count} Pokémon to ${OUT.pathname}`);
